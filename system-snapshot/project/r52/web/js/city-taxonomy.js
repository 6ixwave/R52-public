const aliases = {
  Электроника: "Техника",
  "Компьютерная техника": "Техника",
  Одежда: "Одежда и обувь",
  Дом: "Дом и ремонт",
  Аптека: "Здоровье и аптека",
  Красота: "Красота и уход",
  "Спортивные товары": "Спорт и отдых",
  "Товары для дома": "Дом и ремонт",
  "Товары для школы и офиса": "Канцелярия и офис",
};
export function cityPath(path, product = {}) {
  const result = [...path];
  result[0] = aliases[result[0]] || result[0];
  if (result.length === 1) {
    const name = result[0],
      title = product.title || "";
    let leaf =
      name === "Одежда и обувь"
        ? /куртк|пальто|пуховик/i.test(title)
          ? "Куртки и пальто"
          : /обув|ботин|кроссов|сапог/i.test(title)
            ? "Обувь"
            : /джинс|брюк/i.test(title)
              ? "Джинсы и брюки"
              : "Другое"
        : name === "Прочее"
          ? "Другие товары"
          : "Другое";
    result.push(leaf);
  }
  return result;
}
